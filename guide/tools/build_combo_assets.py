"""Build the COMBO runtime assets from the AI images (prompts: guide/combo-prompts.md).

Sources in assets/ghosts/combo/ (flat magenta or green background, detected from the corner pixel):
  <dedemit>-cutin.png                 close-up of the dedemit mid-strike
  <dedemit>-fx-burst.png              4 frames of the combo hit burst      (falls back to fx-burst.png)
  <dedemit>-fx-afterimage.png         4 frames of the dash/slash trail     (falls back to fx-afterimage.png)
Writes next to them:
  <dedemit>-cutin.webp                cut out, trimmed, 460 px tall
  <dedemit>-burst.webp, -after.webp   4 equal cells, each frame centred in its cell
  manifest.js                         window.COMBO_ASSETS[slot] = { cutin:{src,w,h}, burst:{...}, after:{...} }
game.js shows the cut-in in a slanted panel when a combo starts, the trail behind the fighter, and the burst where the
boosted hit lands. A dedemit without a source keeps the plain combo flash for that part.

Run from the project root:  python guide/tools/build_combo_assets.py [dedemit ...]
Then:                       node guide/tools/update_precache.mjs
"""
import json, sys
from pathlib import Path
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
import build_ghost_assets as B   # noqa: E402  (cutout, split_poses, GHOSTS)

ROOT = Path.cwd()
DIR = ROOT / 'assets/ghosts/combo'
CUTIN_H, BURST_H, AFTER_H = 460, 300, 200


def key_of(path):
    r, g, b = Image.open(path).convert('RGB').getpixel((3, 3))
    return 'green' if g > r and g > b else 'magenta'


def source(name, part):
    own, shared = DIR / f'{name}-{part}.png', DIR / f'{part}.png'
    return own if own.exists() else shared if shared.exists() else None


def build_cutin(name):
    src = DIR / f'{name}-cutin.png'
    if not src.exists(): return None
    img = B.cutout(src, key_of(src))
    k = CUTIN_H / img.height
    img = img.resize((max(1, round(img.width * k)), CUTIN_H), Image.LANCZOS)
    out = DIR / f'{name}-cutin.webp'
    img.save(out, 'WEBP', quality=86, alpha_quality=90, method=6)
    return {'src': out.relative_to(ROOT).as_posix(), 'w': img.width, 'h': img.height}


def build_sheet(name, part, height, tag):
    src = source(name, part)
    if not src: return None
    frames = [p for p, _ in B.split_poses(B.cutout(src, key_of(src)), 4)]
    if not frames: return None
    k = height / max(p.height for p in frames)
    frames = [p.resize((max(1, round(p.width * k)), max(1, round(p.height * k))), Image.LANCZOS) for p in frames]
    cw, ch = max(p.width for p in frames) + 6, height + 6
    sheet = Image.new('RGBA', (cw * len(frames), ch))
    for i, p in enumerate(frames): sheet.alpha_composite(p, (cw * i + (cw - p.width) // 2, (ch - p.height) // 2))
    out = DIR / f'{name}-{tag}.webp'
    sheet.save(out, 'WEBP', quality=86, alpha_quality=90, method=6)
    return {'src': out.relative_to(ROOT).as_posix(), 'cellW': cw, 'cellH': ch, 'frames': len(frames)}


def main(names):
    path = DIR / 'manifest.js'
    assets = {}
    if path.exists():
        txt = path.read_text(encoding='utf-8'); assets = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
    for name in names:
        cfg = B.GHOSTS[name]
        entry = {k: v for k, v in (('cutin', build_cutin(name)), ('burst', build_sheet(name, 'fx-burst', BURST_H, 'burst')),
                                   ('after', build_sheet(name, 'fx-afterimage', AFTER_H, 'after'))) if v}
        if entry: assets[cfg['slot']] = {'ghost': name, **entry}
        print(f'{name} ({cfg["slot"]}): {", ".join(entry) or "no combo sources"}')
    path.write_text('/* Generated by guide/tools/build_combo_assets.py: combo cut-in, hit burst and afterimage sheets per slot. Do not edit. */\n'
                    'window.COMBO_ASSETS = ' + json.dumps(assets, indent=1) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main(sys.argv[1:] or list(B.GHOSTS))
